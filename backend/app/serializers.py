from __future__ import annotations
from .services.status import deviation, deviation_percent

def assignment_dict(a):
    return {
        'id': a.id,
        'process_pk': a.process_id,
        'transformer_pk': a.transformer_id,
        'po_gun_pk': a.po_gun_id,
        'source_row': a.source_row,
        'car_model': a.car_model.name if a.car_model else None,
        'zone': a.zone.name if a.zone else None,
        'process': a.process.name if a.process else None,
        'transformer_id': a.transformer.code if a.transformer else None,
        'po_gun_id': a.po_gun.code if a.po_gun else None,
        'gun_type': a.po_gun.gun_type if a.po_gun else None,
        'current_actual': a.current_actual,
        'current_target': a.current_target,
        'current_min': a.current_min,
        'current_max': a.current_max,
        'current_deviation': deviation(a.current_actual, a.current_target),
        'current_deviation_percent': deviation_percent(a.current_actual, a.current_target),
        'current_unit': a.current_unit,
        'current_status': a.current_status,
        'pressure_actual': a.pressure_actual,
        'pressure_target': a.pressure_target,
        'pressure_min': a.pressure_min,
        'pressure_max': a.pressure_max,
        'pressure_deviation': deviation(a.pressure_actual, a.pressure_target),
        'pressure_deviation_percent': deviation_percent(a.pressure_actual, a.pressure_target),
        'pressure_unit': a.pressure_unit,
        'pressure_status': a.pressure_status,
        'overall_status': a.overall_status,
        'snapshot_label': a.snapshot_label,
        'map_position': a.map_position or (a.process.legacy_map_position if a.process else None),
        'coordinates_verified': bool(a.process.coordinates_verified) if a.process else False,
        'created_at': a.created_at.isoformat() if a.created_at else None,
        'updated_at': a.updated_at.isoformat() if a.updated_at else None,
    }

def action_dict(a):
    assignment = a.assignment
    display_id = a.action_code or (f'LEGACY-ROW-{a.source_row}' if a.source_row else f'CA-REC-{a.id:06d}')
    return {
        'id': a.id,
        'display_id': display_id,
        'action_code': a.action_code,
        'source_row': a.source_row,
        'assignment_id': a.assignment_id,
        'car_model': a.car_model_name or (assignment.car_model.name if assignment else None),
        'zone': a.zone_name or (assignment.zone.name if assignment else None),
        'process': a.process_name or (assignment.process.name if assignment else None),
        'transformer_id': a.transformer_code or (assignment.transformer.code if assignment else None),
        'po_gun_id': a.po_gun_code or (assignment.po_gun.code if assignment else None),
        'abnormal_parameter': a.abnormal_parameter,
        'actual_reading': a.actual_reading,
        'target_or_limit': a.target_or_limit,
        'target_or_limit_text': a.target_or_limit_text,
        'problem_description': a.problem_description,
        'corrective_action': a.corrective_action_text,
        'pic': a.pic,
        'date_reported': a.date_reported.isoformat() if a.date_reported else None,
        'due_date': a.due_date.isoformat() if a.due_date else None,
        'action_status': a.action_status,
        'verified_by': a.verified_by,
        'verification_date': a.verification_date.isoformat() if a.verification_date else None,
        'remarks': a.remarks,
        'verification_status': a.verification_status,
        'source_label': a.source_label,
        'created_at': a.created_at.isoformat() if a.created_at else None,
        'updated_at': a.updated_at.isoformat() if a.updated_at else None,
    }
